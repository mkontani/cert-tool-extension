// Regenerates src/lint/data/tlds.ts from the IANA root zone TLD list.
// The BR defines an "Internal Name" as one that does not end with a TLD in this list.
// Usage: node scripts/update-tlds.mjs
import { writeFile } from 'node:fs/promises';

const SOURCE = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';
const OUT = new URL('../src/lint/data/tlds.ts', import.meta.url);

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`Failed to fetch ${SOURCE}: ${res.status}`);
const lines = (await res.text()).split('\n').map(l => l.trim()).filter(Boolean);

const version = lines[0].match(/^# Version (\d+)/)?.[1];
if (!version) throw new Error('Unexpected TLD list header');
const tlds = lines.slice(1).map(l => l.toLowerCase());
if (tlds.length < 1000 || tlds.some(t => !/^[a-z0-9-]+$/.test(t))) {
    throw new Error('Unexpected TLD list contents');
}

const body = `// Generated by scripts/update-tlds.mjs from ${SOURCE} — do not edit by hand.
export const TLD_LIST_VERSION = '${version}';

export const TLDS: ReadonlySet<string> = new Set(
    '${tlds.join(' ')}'.split(' '),
);
`;
await writeFile(OUT, body);
console.log(`wrote ${tlds.length} TLDs (version ${version})`);
